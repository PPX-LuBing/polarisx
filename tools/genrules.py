#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""从 Python 版 ixpanel 提取 Clash 规则表，生成 Go 源码 internal/panel/rules.go。

用生成而不是手抄：Go 的 map 迭代顺序随机，YAML 必须与 Python 的 dict 顺序一致，
所以生成有序切片。
"""
import importlib.util
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "internal", "panel", "rules.go")
IXPANEL_SRC = os.environ.get("IXPANEL_SRC", "/Users/ice/WorkSpace/ixrelay/src/ixpanel.py")


def load():
    spec = importlib.util.spec_from_file_location("ixpanel", IXPANEL_SRC)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def q(s):
    return '"%s"' % str(s).replace("\\", "\\\\").replace('"', '\\"')


def main():
    ix = load()
    out = []
    out.append("// Code generated by tools/genrules.py from the Python implementation. DO NOT EDIT.\n")
    out.append("package panel\n")
    out.append("// NamedProvider 是有序的规则源（顺序必须与 Python 的 dict 一致，YAML 才对得上）。")
    out.append("type NamedProvider struct {\n\tName                        string\n\tBehavior, URL, File         string\n}\n")
    out.append("// Group 是 Clash 服务分组（第一个成员为默认选中项）。")
    out.append("type Group struct {\n\tName    string\n\tMembers []string\n}\n")

    for var, table in (("CommunityProviders", ix.CLASH_RULE_PROVIDERS),
                       ("MyClashProviders", ix.MYCLASH_PROVIDERS)):
        out.append("// %s 共 %d 个。" % (var, len(table)))
        out.append("var %s = []NamedProvider{" % var)
        for name, (beh, url, fn) in table.items():
            out.append("\t{%s, %s, %s, %s}," % (q(name), q(beh), q(url), q(fn)))
        out.append("}\n")

    for var, table in (("CommunityGroups", ix.CLASH_RULE_GROUPS),
                       ("MyClashGroups", ix.MYCLASH_GROUPS)):
        out.append("// %s 共 %d 个。" % (var, len(table)))
        out.append("var %s = []Group{" % var)
        for name, members in table.items():
            out.append("\t{%s, []string{%s}}," % (q(name), ", ".join(q(m) for m in members)))
        out.append("}\n")

    out.append("// PresetProviders / PresetGroups：预设 -> 规则源 / 分组。")
    out.append("var PresetProviders = map[string][]NamedProvider{")
    for k, v in ix.PRESET_PROVIDERS.items():
        out.append("\t%s: %s," % (q(k), {"community": "CommunityProviders",
                                         "myclash": "MyClashProviders"}[k]))
    out.append("}\n")
    out.append("var PresetGroups = map[string][]Group{")
    for k, v in ix.PRESET_GROUPS.items():
        out.append("\t%s: %s," % (q(k), {"community": "CommunityGroups",
                                         "myclash": "MyClashGroups"}[k]))
    out.append("}\n")

    out.append("// RulePresets：各预设的规则列表（RULE-PORT-PLACEHOLDER 由 direct_ports 展开）。")
    out.append("var RulePresets = map[string][]string{")
    for name, rules in ix.CLASH_RULE_PRESETS.items():
        out.append("\t%s: {" % q(name))
        for r in rules:
            out.append("\t\t%s," % q(r))
        out.append("\t},")
    out.append("}\n")

    out.append("// DefaultRulePreset 与 Python 版 DEFAULT_SETTINGS 对齐。")
    out.append("const DefaultRulePreset = %s\n" % q(ix.DEFAULT_SETTINGS["clash_rules"]))

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    n_prov = len(ix.CLASH_RULE_PROVIDERS) + len(ix.MYCLASH_PROVIDERS)
    n_rules = sum(len(v) for v in ix.CLASH_RULE_PRESETS.values())
    print("已生成 %s" % OUT)
    print("  规则源 %d 个 / 分组 %d 个 / 预设 %d 个 / 规则共 %d 条"
          % (n_prov, len(ix.CLASH_RULE_GROUPS) + len(ix.MYCLASH_GROUPS),
             len(ix.CLASH_RULE_PRESETS), n_rules))


if __name__ == "__main__":
    main()
